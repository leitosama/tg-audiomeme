// Writes tgcloud/lib/config.js from environment variables (ADR-0003). tgcloud has no
// env vars at runtime, so each bot instance's config is baked in at deploy time:
// CI runs this with the deploying GitHub Environment's variables, `npm run config`
// runs it locally from `.env`.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const CONFIG_PATH = fileURLToPath(new URL('../tgcloud/lib/config.js', import.meta.url));

/**
 * Renders the config module's source, or throws if a variable is missing or invalid.
 * @param {Record<string, string | undefined>} env
 * @returns {string}
 */
export function renderConfig(env) {
  const adminId = Number(env.ADMIN_ID);
  if (!env.ADMIN_ID || !Number.isSafeInteger(adminId) || adminId <= 0) {
    throw new Error(
      `ADMIN_ID must be a positive integer Telegram user ID, got "${env.ADMIN_ID ?? ''}"`,
    );
  }
  const approval = env.REQUIRE_APPROVAL ?? 'false';
  if (approval !== 'true' && approval !== 'false') {
    throw new Error(`REQUIRE_APPROVAL must be "true" or "false", got "${approval}"`);
  }
  return [
    '// Generated by scripts/gen-config.js (npm run config) — do not edit or commit.',
    `export const ADMIN_ID = ${adminId};`,
    `export const REQUIRE_APPROVAL = ${approval};`,
    `export const MINI_APP_URL = ${JSON.stringify(miniAppUrl(env.TGCLOUD_TOKEN))};`,
    '',
  ].join('\n');
}

/**
 * The Converter's URL: tgcloud serves a bot's Mini App at `https://app<id>.tgcloud.ai/`,
 * and its token is `app<id>:<secret>`. No token → '' (no Converter button).
 * @param {string | undefined} token
 */
function miniAppUrl(token) {
  if (!token) return '';
  const match = /^app(\d+):./.exec(token);
  // Never echo the token: it's a secret and this message ends up in CI logs.
  if (!match) throw new Error('TGCLOUD_TOKEN must look like app<id>:<secret>');
  return `https://app${match[1]}.tgcloud.ai/`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    writeFileSync(CONFIG_PATH, renderConfig(process.env));
    console.log(`Wrote ${CONFIG_PATH}`);
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
